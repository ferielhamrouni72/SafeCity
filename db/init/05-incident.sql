CREATE TABLE IF NOT EXISTS incident (
  id int unsigned NOT NULL AUTO_INCREMENT PRIMARY KEY,
  titre varchar(120) NOT NULL,
  type enum('ACCIDENT','INCENDIE','INONDATION','FUITE_EAU','ARBRE_TOMBE','NID_DE_POULE','INFRASTRUCTURE','AUTRE') NOT NULL,
  description text NULL,
  lieu varchar(150) NULL,
  latitude decimal(9,6) NOT NULL,
  longitude decimal(9,6) NOT NULL,
  statut enum('NOUVEAU','VALIDE','EN_COURS','RESOLU','REJETE','A_VERIFIER') NOT NULL DEFAULT 'NOUVEAU',
  gravite enum('FAIBLE','MOYENNE','ELEVEE','CRITIQUE') NULL,
  priorite enum('NORMALE','URGENTE') NOT NULL DEFAULT 'NORMALE',
  confiance_ia decimal(5,2) NULL,
  nombre_temoins int unsigned NOT NULL DEFAULT 1,
  citoyen_id int unsigned NOT NULL,
  agent_id int unsigned NULL,
  date_creation datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  date_modification datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  date_prise_en_charge datetime NULL,
  date_resolution datetime NULL,
  KEY idx_incident_statut_date (statut, date_creation),
  KEY idx_incident_date (date_creation),
  CONSTRAINT chk_incident_lat CHECK (latitude BETWEEN -90 AND 90),
  CONSTRAINT chk_incident_lng CHECK (longitude BETWEEN -180 AND 180),
  CONSTRAINT fk_incident_citoyen FOREIGN KEY (citoyen_id) REFERENCES utilisateur (id) ON DELETE CASCADE,
  CONSTRAINT fk_incident_agent FOREIGN KEY (agent_id) REFERENCES utilisateur (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;